INSERT INTO "Upazilas" ("Id", "DistrictId", "Name", "NormalizedName", "IsActive")
SELECT s.id::uuid, t."Id", s.name, s.normalized, true
FROM seed_upazilas s
JOIN "Divisions" d ON d."NormalizedName" = s.division AND NOT d."IsDeleted"
JOIN "Districts" t ON t."DivisionId" = d."Id" AND t."NormalizedName" = s.district AND NOT t."IsDeleted"
ON CONFLICT DO NOTHING;

DO $$
DECLARE missing integer;
BEGIN
    SELECT count(*) INTO missing
    FROM seed_upazilas s
    WHERE NOT EXISTS (SELECT 1 FROM "Upazilas" u WHERE u."Id" = s.id::uuid)
      AND NOT EXISTS (
        SELECT 1 FROM "Upazilas" u
        JOIN "Districts" t ON t."Id" = u."DistrictId"
        JOIN "Divisions" d ON d."Id" = t."DivisionId"
        WHERE d."NormalizedName" = s.division AND t."NormalizedName" = s.district AND u."NormalizedName" = s.normalized
          AND NOT u."IsDeleted" AND NOT t."IsDeleted" AND NOT d."IsDeleted");
    IF missing > 0 THEN
        RAISE EXCEPTION '% upazila(s) could not be added because their district is missing or was deleted; run seed-divisions.sql and seed-districts.sql first (a deleted district stays deleted).', missing;
    END IF;
END $$;

COMMIT;

